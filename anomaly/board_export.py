"""the on-device detector: fit it, prove its C port's algorithm, export it to the board.

the board has never had a model. it streams to the fleet master, the master
scores, and without the master the board shows no verdict at all. that leaves
milestone M2 (the full loop ON the device) open, and it leaves the privacy
claim false: the raw waveform has to leave the board to be judged.

the autoencoder is 4 MB int8 and needs TFLite Micro. the statistical baseline
is ten features and a 10x10 matrix -- 520 bytes of model -- and it runs on the
board in plain C++. the price is measured, not guessed: leave-one-subject-out
on WESAD it scores PR-AUC 0.635 / recall@90spec 0.437 against the deployed
autoencoder's 0.706 / 0.545 (anomaly/RESULTS.md). that gap IS the accuracy cost
of running on-device, which is the number O7 asks for.

what goes on the board, all in sketch_aug3a/:

    board_model.h     GENERATED by this script: the fitted detector, the filter,
                      the runtime constants (mirrored from anomaly.fleet and
                      anomaly.quality), and self-test vectors
    board_detector.h  the algorithm, hand-written C++: quality gate, features,
                      Mahalanobis, the live self-referencing scale

there is no host C compiler on the dev machine, so the port is verified in
three layers:

    1. `--check`: a loop-for-loop Python mirror of every C routine (odd-extended
       zero-phase filtering, scipy's find_peaks semantics, a kiss-style
       mixed-radix FFT, the movement gate) is compared against scipy/numpy and
       anomaly.quality on real WESAD windows. this proves the ALGORITHM.
    2. the header compiles with the ESP32 cross-compiler (see COMMANDS.md).
    3. the board runs the baked self-test vectors through the C++ at boot and
       reports pass/fail on serial and /health. this proves the TRANSLATION.

    python -m anomaly.board_export               # fit + write board_model.h
    python -m anomaly.board_export --check 300   # verify the mirror on 300 windows
"""
