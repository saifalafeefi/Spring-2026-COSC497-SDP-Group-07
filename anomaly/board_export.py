def _c(v: float) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)) or (hasattr(v, "dtype") and np.isnan(v)):
        return "NAN"
    t = "%.9g" % float(v)
    if not any(ch in t for ch in ".en"):     # "15f" is not a C literal; "15.f" is
        t += "."
    return t + "f"


def _cd(v: float) -> str:
    t = "%.17g" % float(v)
    return t if any(ch in t for ch in ".en") else t + ".0"


def _arr(vals, per=8, fmt=_c) -> str:
    vals = [fmt(v) for v in vals]
    return ",\n    ".join(", ".join(vals[i:i + per]) for i in range(0, len(vals), per))


def export(data, out: str = OUT) -> dict:
    from . import fleet

    calm = np.concatenate([X[c == NORMAL] for X, c in data.values()])
    print("  fitting on %d calm windows from %d WESAD subjects…" % (len(calm), len(data)))
    t0 = time.time()
    F = np.array([extract_features(w, FS) for w in calm], dtype=np.float32)
    det = MahalanobisDetector().fit_features(F)
    print("  features in %.0f s" % (time.time() - t0))

    def score(w):
        f = np.array([extract_features(w, FS)], dtype=np.float32)
        return float(np.sqrt(max(float(det.score_features(f)[0]), 0.0)))

    # self-test windows: one calm and one stress, plus a movement history built
    # from the calm one that the gate must STITCH and REPAIR. WESAD wrist BVP is
    # noisy enough that many calm windows break the device-tuned envelope on
    # their own, so the calm window is searched for rather than hard-coded.
    def gate_history(w):
        # BD_TEST_X[0] twice (120 s), seconds 70-74 at 6x amplitude, one knock
        # at 5000 of 100 step-sigmas: caught by the spike test (60), small
        # enough that its second survives the envelope and gets repaired
        h = np.concatenate([w, w]).astype(np.float32)
        h[70 * FS:75 * FS] *= np.float32(6.0)
        d = np.diff(w.astype(np.float64))
        kn = np.float32(100.0 * np.median(np.abs(d - np.median(d))) * 1.4826)
        h[5000] += kn
        return h, kn

    X, c = data["S5"]
    calm_idx, stress_idx = np.flatnonzero(c == NORMAL), np.flatnonzero(c == POSITIVE)
    for j in calm_idx:
        hist, knock = gate_history(X[j])
        r = m_clean_window(hist, WIN, FS)
        if r["ok"] and r["dropped"] and r["repaired"]:
            break
    else:
        raise SystemExit("no S5 calm window both stitches and repairs; widen the search")
    gate = quality.clean_window(hist, WIN, FS)
    assert gate["window"] is not None and gate["dropped"] == r["dropped"]
    tests = [X[j], X[stress_idx[len(stress_idx) // 2]]]
    tf = [extract_features(w, FS) for w in tests]
    ts = [score(w) for w in tests]
    gw = gate["window"].astype(np.float64)
    gate_sum, gate_sq = float(gw.sum()), float((gw * gw).sum())

    params = np.concatenate([det.median_, det.mu_, det.sd_, det.center_, det.inv_cov_.ravel()])
    tag = "maha-wesad%d-%s" % (len(data), hashlib.sha256(params.astype(np.float32).tobytes()).hexdigest()[:10])

    L = []
    w = L.append
    w("// GENERATED by `python -m anomaly.board_export` -- do not edit by hand.")
    w("// the on-device detector: Mahalanobis on %d features, fitted on %d calm" % (N_FEATURES, len(calm)))
    w("// WESAD windows from %d subjects. LOSO on WESAD: PR-AUC 0.635 / recall@90spec" % len(data))
    w("// 0.437, against the host autoencoder's 0.706 / 0.545 -- the on-device cost.")
    w("// the algorithm lives in board_detector.h; this file is only numbers.")
    w("#pragma once")
    w("#include <math.h>")
    w("")
    w('#define BD_MODEL_TAG "%s"' % tag)
    w("#define BD_FS %d" % FS)
    w("#define BD_WIN %d                 // 60 s at 64 Hz: the window the model scores" % WIN)
    w("#define BD_HIST %d                // 150 s: slack to drop movement and back-fill" % fleet.HIST)
    w("#define BD_NF %d" % N_FEATURES)
    w("#define BD_NBINS %d" % NBINS)
    w("#define BD_BAND_LO %d             // rfft bins 0.7..3.0 Hz, inclusive" % BAND_LO)
    w("#define BD_BAND_HI %d" % BAND_HI)
    w("#define BD_PEAK_DIST %d           // find_peaks distance, samples" % PEAK_DIST)
    w("#define BD_PADLEN %d              // sosfiltfilt odd-extension length" % PADLEN)
    w("")
    w("// butter(2, [0.7, 3.0], btype='band', fs=64) and its sosfilt_zi, in double:")
    w("// the zero-phase pass runs in double so a near-tie peak cannot flip on rounding")
    w("static const double BD_SOS[2][6] = {")
    for r in SOS:
        w("  {%s}," % ", ".join(_cd(v) for v in r))
    w("};")
    w("static const double BD_ZI[2][2] = {")
    for r in ZI:
        w("  {%s}," % ", ".join(_cd(v) for v in r))
    w("};")
    w("")
    w("// the fitted detector (anomaly.baseline.MahalanobisDetector)")
    w("// features: " + ", ".join(FEATURE_NAMES))
    for name, arr in (("BD_MEDIAN", det.median_), ("BD_MU", det.mu_),
                      ("BD_SD", det.sd_), ("BD_CENTER", det.center_)):
        w("static const float %s[BD_NF] = {\n    %s};" % (name, _arr(arr, per=5)))
