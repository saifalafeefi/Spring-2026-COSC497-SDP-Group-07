# every function below is written the way the C++ is: explicit loops, explicit
# indices, no library call whose semantics the C would have to guess. numpy is
# used only where the C does the same arithmetic in a plain loop.

def m_filtfilt(x: np.ndarray) -> np.ndarray:
    """scipy.signal.sosfiltfilt(SOS, x) with its defaults: odd extension by
    PADLEN, sosfilt_zi steady state scaled by the first sample of each pass."""
    n, p = len(x), PADLEN
    ext = np.empty(n + 2 * p)
    for i in range(p):
        ext[i] = 2.0 * x[0] - x[p - i]
    ext[p:p + n] = x
    for j in range(p):
        ext[p + n + j] = 2.0 * x[n - 1] - x[n - 2 - j]

    def run(buf, scale):
        z = ZI * scale
        out = np.empty_like(buf)
        for k in range(len(buf)):
            v = buf[k]
            for s in range(len(SOS)):
                b0, b1, b2, _, a1, a2 = SOS[s]
                y = b0 * v + z[s, 0]
                z[s, 0] = b1 * v - a1 * y + z[s, 1]
                z[s, 1] = b2 * v - a2 * y
                v = y
            out[k] = v
        return out

    y = run(ext, ext[0])
    y = run(y[::-1].copy(), y[-1])
    return y[::-1][p:p + n]


def m_find_peaks(x: np.ndarray, distance: int, prominence) -> list:
    """scipy.signal.find_peaks(x, distance=, prominence=): local maxima (plateaus
    resolved to their midpoint), then distance by descending height, then
    prominence with no window limit."""
    n = len(x)
    peaks = []
    i, i_max = 1, n - 1
    while i < i_max:
        if x[i - 1] < x[i]:
            ahead = i + 1
            while ahead < i_max and x[ahead] == x[i]:
                ahead += 1
            if x[ahead] < x[i]:
                peaks.append((i + ahead - 1) // 2)
                i = ahead
        i += 1
    m = len(peaks)
    keep = [True] * m
    # ascending by height; ties by position (numpy's argsort leaves ties
    # unspecified -- exact float ties between peaks do not occur in practice)
    order = sorted(range(m), key=lambda j: (x[peaks[j]], j))
    for r in range(m - 1, -1, -1):
        j = order[r]
        if not keep[j]:
            continue
        k = j - 1
        while k >= 0 and peaks[j] - peaks[k] < distance:
            keep[k] = False
            k -= 1
        k = j + 1
        while k < m and peaks[k] - peaks[j] < distance:
            keep[k] = False
            k += 1
    peaks = [pk for pk, kp in zip(peaks, keep) if kp]
    if prominence is None:
        return peaks
    out = []
    for pk in peaks:
        h = x[pk]
        lmin, i = h, pk
        while i >= 0 and x[i] <= h:
            if x[i] < lmin:
                lmin = x[i]
            i -= 1
        rmin, i = h, pk
        while i <= n - 1 and x[i] <= h:
            if x[i] < rmin:
                rmin = x[i]
            i += 1
        if h - max(lmin, rmin) >= prominence:
            out.append(pk)
    return out


def _factor(n: int) -> list:
    """kiss_fft's factorisation: 4s first, then 2, then odd primes."""
    out, p = [], 4
    while n > 1:
        while n % p:
            p = 2 if p == 4 else (3 if p == 2 else p + 2)
        n //= p
        out.append((p, n))
    return out


def m_fft(x: np.ndarray) -> np.ndarray:
    """a kiss-style recursive mixed-radix DIT FFT with a generic butterfly --
    the exact recursion board_detector.h uses."""
    N = len(x)
    tw = np.exp(-2j * np.pi * np.arange(N) / N)
    fac = _factor(N)
    out = np.zeros(N, complex)

    def work(fo: int, fi: int, fstride: int, level: int):
        p, m = fac[level]
        if m == 1:
            for q in range(p):
                out[fo + q] = x[fi + q * fstride]
        else:
            for q in range(p):
                work(fo + q * m, fi + q * fstride, fstride * p, level + 1)
        scratch = np.empty(p, complex)
        for u in range(m):
            k = u
            for q1 in range(p):
                scratch[q1] = out[fo + k]
                k += m
            k = u
            for q1 in range(p):
                acc = scratch[0]
                tidx = 0
                for q in range(1, p):
                    tidx += fstride * k
                    if tidx >= N:
                        tidx -= N
                    acc += scratch[q] * tw[tidx]
                out[fo + k] = acc
                k += m

    work(0, 0, 1, 0)
    return out


def m_features(window: np.ndarray, fft=np.fft.rfft) -> np.ndarray:
    """features.extract_features, the way board_detector.h computes it."""
    x = np.asarray(window, dtype=np.float64)
    n = len(x)
    mean = x.sum() / n
    sd = math.sqrt(((x - mean) ** 2).sum() / n)
    x = (x - mean) / (sd + 1e-8)
    f = np.full(N_FEATURES, np.nan)
    bp = m_filtfilt(x)
    bmean = bp.sum() / n
    bsd = math.sqrt(((bp - bmean) ** 2).sum() / n)
    f[4] = bsd
    f[5] = bp.max() - bp.min()
    f[9] = np.abs(np.diff(x)).sum() / (n - 1)
    peaks = m_find_peaks(bp, PEAK_DIST, bsd * 0.3 if bsd > 0 else None)
    if len(peaks) >= 3:
        ibi = np.diff(peaks) / FS
        s = np.sort(ibi)
        k = len(s)
        med = s[k // 2] if k % 2 else 0.5 * (s[k // 2 - 1] + s[k // 2])
        f[0] = 60.0 / med
        im = ibi.sum() / k
        f[1] = math.sqrt(((ibi - im) ** 2).sum() / k)
        d = np.diff(ibi)
        f[2] = math.sqrt((d ** 2).sum() / len(d))
    f[3] = len(peaks) / (n / FS)
    X = fft(x)[:NBINS]
    psd = X.real ** 2 + X.imag ** 2
    tot = psd.sum() + 1e-12
    band = psd[BAND_LO:BAND_HI + 1]
    bs = band.sum()
    f[6] = (BAND_LO + int(np.argmax(band))) * FS / float(n) if bs > 0 else np.nan
    f[7] = bs / tot
    p = psd / tot
    f[8] = -(p * np.log(p + 1e-12)).sum() / math.log(NBINS)
    return f


def m_percentile(a, q: float) -> float:
    """numpy's default (linear) percentile."""
    s = sorted(a)
    pos = (len(s) - 1) * q / 100.0
    lo = int(math.floor(pos))
    hi = min(lo + 1, len(s) - 1)
    return s[lo] + (pos - lo) * (s[hi] - s[lo])


def m_median(a) -> float:
    return m_percentile(a, 50.0)


def m_std(a) -> float:
    a = np.asarray(a, np.float64)
    mu = a.sum() / len(a)
    return math.sqrt(((a - mu) ** 2).sum() / len(a))


def m_artifact_mask(w) -> np.ndarray:
    w = np.asarray(w, np.float64)
    n = len(w)
    d = np.empty(n)
    d[0] = 0.0
    d[1:] = w[1:] - w[:-1]
    med = m_median(d)
    mad = m_median(np.abs(d - med)) * 1.4826
    mask = np.zeros(n, bool)
    if mad < quality.MIN_MAD:
        return mask
    for i in range(n):
        if abs(d[i] - med) > quality.SPIKE_Z * mad:
            lo, hi = max(i - quality.SPREAD, 0), min(i + quality.SPREAD + 1, n)
            mask[lo:hi] = True
    if not mask.any():
        return mask
    # bridge: runs of the mask, and the displaced plateaus between them
    runs, i = [], 0
    while i < n:
        if mask[i]:
            j = i
            while j < n and mask[j]:
                j += 1
            runs.append((i, j))
            i = j
        else:
            i += 1
    if len(runs) < 2:
        return mask
    good = w[~mask]
    if len(good) < 2:
        return mask
    gmed = m_median(good)
    gmad = m_median(np.abs(good - gmed)) * 1.4826
    if gmad < quality.MIN_MAD:
        return mask
    out = mask.copy()
    for (_, end), (start, _) in zip(runs, runs[1:]):
        if start - end <= 0 or start - end > quality.BRIDGE_GAP:
            continue
        if abs(m_median(w[end:start]) - gmed) > quality.BRIDGE_Z * gmad:
            out[end:start] = True
    return out


def m_repair(w, mask) -> np.ndarray:
    w = np.asarray(w, np.float32).copy()
    n = len(w)
    if not mask.any() or (~mask).sum() < 2:
        return w
    i = 0
    while i < n:
        if not mask[i]:
            i += 1
            continue
        j = i
        while j < n and mask[j]:
            j += 1
        a, b = i - 1, j                      # nearest good either side
        for k in range(i, j):
            if a < 0:
                w[k] = w[b]
            elif b >= n:
                w[k] = w[a]
            else:
                w[k] = w[a] + (k - a) * (float(w[b]) - float(w[a])) / (b - a)
        i = j
    return w


def m_clean_window(hist, need: int = WIN, fs: int = FS) -> dict:
    """quality.clean_window, the way board_detector.h does it."""
    hist = np.asarray(hist, np.float32)
    n = max(1, int(fs * quality.ENVELOPE_SEC))
    need_secs = -(-need // n)
    k = len(hist) // n
    out = {"window": None, "dropped": 0, "quality": 0.0, "ok": False, "repaired": 0}
    if k < need_secs:
        return out
    amp = [m_std(hist[i * n:(i + 1) * n]) for i in range(k)]
    ref = m_percentile(amp, quality.ENVELOPE_REF_Q)
    if ref < quality.MIN_MAD:
        return out
    picks = []
    for i in range(k - 1, -1, -1):
        if amp[i] / ref <= quality.ENVELOPE_RATIO:
            picks.append(i)
            if len(picks) == need_secs:
                break
    if len(picks) < need_secs:
        return out
    picks.sort()
    w = np.concatenate([hist[i * n:(i + 1) * n] for i in picks])[:need]
    mask = m_artifact_mask(w)
    bad = mask.sum() / len(w)
    if bad and bad <= quality.MAX_REPAIR:
        w = m_repair(w, mask)
        out["repaired"] = int(mask.sum())
    span = picks[-1] - picks[0] + 1
    out.update(window=w, dropped=span - need_secs, quality=need_secs / span, ok=True)
    return out


