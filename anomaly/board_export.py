def load_cache():
    if not os.path.exists(CACHE):
        raise SystemExit("no window cache at %s -- run `python -m anomaly.run --model baseline` "
                         "once to build it" % CACHE)
    z = np.load(CACHE)
    subs = sorted({k[:-2] for k in z.files if k.endswith("_X")}, key=lambda s: int(s[1:]))
    return {s: (z[s + "_X"], z[s + "_c"]) for s in subs}


def check(data, n_windows: int, seed: int = 0) -> bool:
    rng = np.random.default_rng(seed)
    pool = [(s, i) for s, (X, c) in data.items() for i in range(len(X))]
    pick = [pool[j] for j in rng.choice(len(pool), size=min(n_windows, len(pool)), replace=False)]
    t0 = time.time()

    # 1. features: mirror (numpy FFT) vs features.extract_features
    err = np.zeros(N_FEATURES)
    nan_mismatch = 0
    for s, i in pick:
        w = data[s][0][i]
        a, b = m_features(w), extract_features(w, FS)
        both = np.isnan(a) & np.isnan(b)
        nan_mismatch += int((np.isnan(a) != np.isnan(b)).sum())
        e = np.where(both, 0.0, np.abs(a - b) / np.maximum(1.0, np.abs(b)))
        err = np.maximum(err, np.nan_to_num(e, nan=np.inf))
    print("  features, mirror vs anomaly.features on %d windows (%.0f s):" % (len(pick), time.time() - t0))
    for name, e in zip(FEATURE_NAMES, err):
        print("    %-17s max rel err %.2e" % (name, e))
    ok = bool(err.max() < 1e-9 and nan_mismatch == 0)
    print("    NaN disagreements: %d   -> %s" % (nan_mismatch, "PASS" if ok else "FAIL"))

    # 2. the FFT recursion vs numpy, on real windows
    fe = 0.0
    for s, i in pick[:3]:
        x = data[s][0][i].astype(np.float64)
        ref = np.fft.fft(x)
        fe = max(fe, float(np.abs(m_fft(x) - ref).max() / np.abs(ref).max()))
    fok = fe < 1e-10
    print("  mixed-radix FFT (factors %s) vs numpy: max rel err %.1e -> %s" % (
        [p for p, _ in _factor(WIN)], fe, "PASS" if fok else "FAIL"))

    # 3. the movement gate vs anomaly.quality on synthetic disturbances
    qok = True
    kinds = {"refused": 0, "whole": 0, "stitched": 0, "repaired": 0}
    for trial in range(40):
        s, i = pick[trial % len(pick)]
        base = np.concatenate([data[s][0][i], data[s][0][(i + 12) % len(data[s][0])]])[:150 * FS]
        hist = base.astype(np.float32).copy()
        r2 = np.random.default_rng(trial)
        for _ in range(int(r2.integers(0, 4))):           # bursts of movement
            a = int(r2.integers(0, len(hist) - 6 * FS))
            hist[a:a + int(r2.integers(1, 6)) * FS] *= float(r2.uniform(2, 8))
        # sample-level knocks, sized on the spike test's own scale (the robust
        # spread of sample-to-sample steps): big enough to be caught, small
        # enough that their second survives the envelope and gets REPAIRED
        d = np.diff(base.astype(np.float64))
        step = float(np.median(np.abs(d - np.median(d))) * 1.4826)
        for _ in range(int(r2.integers(1, 4))):
            a = int(r2.integers(1, len(hist) - 3))
            hist[a] += float(r2.uniform(80, 150)) * step
        want = quality.clean_window(hist, WIN, FS)
        got = m_clean_window(hist, WIN, FS)
        if want["window"] is None:
            kinds["refused"] += 1
        else:
            kinds["stitched" if want["dropped"] else "whole"] += 1
        kinds["repaired"] += int(got["repaired"] > 0)
        same = (want["window"] is None) == (not got["ok"])
        if same and got["ok"]:
            same = (want["dropped"] == got["dropped"] and
                    np.allclose(want["window"], got["window"], rtol=0, atol=1e-5))
        qok &= bool(same)
    # every path has to have been exercised, or a PASS says nothing about it
    qok &= kinds["refused"] > 0 and kinds["stitched"] > 0 and kinds["repaired"] > 0
    print("  movement gate vs anomaly.quality on 40 disturbed histories %s -> %s" % (
        kinds, "PASS" if qok else "FAIL"))
    return ok and fok and qok


